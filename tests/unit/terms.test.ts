/**
 * 利用規約の追加（2026-09-13 の点検・PR-3 の 20）。
 *
 * 文面は検収側が渡した本文から**改変しない。** 描画した HTML に、渡された文が
 * **一字一句そのまま**入っていることを見る（JSX の改行で文が割れていないか、も含めて）。
 */
import { describe, it, expect } from "vitest";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import TermsPage from "@/app/terms/page";

const html = renderToStaticMarkup(createElement(TermsPage));
/** タグを外した本文 */
const text = html.replace(/<[^>]+>/g, "");

describe("第6条 禁止事項に2項目を足す", () => {
  it("既存3項目のあとに、渡された2項目がそのまま入る", () => {
    const items = [...html.matchAll(/<li>(.*?)<\/li>/g)].map((m) => m[1]);
    expect(items).toEqual([
      "他者のアカウントへの不正なアクセス、またはその試み",
      "本サービスの提供を妨げる行為",
      "権限のないデータを接続する行為",
      "同一の会社で複数のアカウントを作成する行為、または他者に自分のアカウントを使わせる行為",
      "ボット、スクレイピング、API の直接呼び出しなど、本サービスの画面を経由しない自動化された手段で本サービスにアクセスする行為",
    ]);
  });
});

describe("第7条 利用の制限・停止を新設し、以降の条番号を1つずつ後ろにずらす", () => {
  it("見出しは 1〜9 条で、7 が利用の制限・停止、8 が変更・終了、9 が準拠法", () => {
    const headings = [...html.matchAll(/<h2>(.*?)<\/h2>/g)].map((m) => m[1]);
    expect(headings).toEqual([
      "1. 本規約について",
      "2. アカウント",
      "3. 接続する会社情報",
      "4. 従業員のデータを含む場合",
      "5. 出力の位置づけ",
      "6. 禁止事項",
      "7. 利用の制限・停止",
      "8. サービスの変更・終了",
      "9. 準拠法",
    ]);
  });

  it("第7条の3段落が、渡された文のまま入る", () => {
    for (const sentence of [
      "提供者は、利用者が本規約に違反した場合、または本サービスの安全な提供に支障があると判断した場合、事前の通知なく、アカウントの停止、利用の制限、接続の解除を行うことがあります。",
      "本サービスには、機能ごとに利用回数や取り込める件数の上限を設けることがあります。上限に達した場合、その機能は一定期間ご利用いただけません。上限の値は、提供者が予告なく変更することがあります。",
      // **1段落目（提供者の判断による停止・制限）だけが通知の対象。** 上限（2段落目）は自動（#137 の検収で決定）
      "本条第1項の停止または制限を行った場合、提供者は登録されたメールアドレスにその旨を通知します。利用者は、通知に記載された窓口から異議を申し出ることができます。",
    ]) {
      expect(text).toContain(sentence);
    }
  });
});

describe("最終更新日", () => {
  it("本番反映日（merge 日の 2026-09-15）に更新した", () => {
    expect(text).toContain("2026-09-15");
    expect(text).not.toContain("2026-08-19");
  });
});
